// Generates the writing-state keyframes so the pencil TIP follows the strokes drawn on the notebook exactly.
//   node scripts/mino-art/gen-rig-writing.mjs
// Kinematics (master px, y down; CSS rotate() is clockwise):  tip = S + R(θarm)(G + R(θwrist)(T0 − G) − S) + t
//   S shoulderL, G pencil grip, T0 pencil tip in the neutral pose, t = the arm group's translate (what we solve for).
// The strokes live in the notebook group, which sits in the right arm rotated by a constant θr about shoulderR, so the
// target for a stroke point P is  SR + R(θr)(P − SR).  Output: a generated CSS file + a generated TS module.
import fs from 'node:fs';
const manifest = JSON.parse(fs.readFileSync(new URL('../../public/mino/coach/manifest.json', import.meta.url)));
const piv = manifest.pivots;
const STAGE = { w: 1200, h: 1088 };
const S = piv.shoulderL, G = piv.pencilGrip, SR = piv.shoulderR, T0 = [700, 768]; // T0 measured on layer-pencil (graphite tip)
const TH_ARM = -12, TH_WRIST = -20, TH_R = 15;
const rot = (p, deg) => { const a = (deg * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a); return [p[0] * c - p[1] * s, p[0] * s + p[1] * c]; };
const add = (a, b) => [a[0] + b[0], a[1] + b[1]], sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const tipLocal = add(G, rot(sub(T0, G), TH_WRIST));
const armTip = add(S, rot(sub(tipLocal, S), TH_ARM)); // tip with zero translate
const target = (P) => add(SR, rot(sub(P, SR), TH_R));
const translateFor = (P, lift = 0) => { const T = target(P); T[1] -= lift; return sub(T, armTip); };

// strokes in notebook-local master px: three lines of small handwriting waves
const LINES = [{ y: 705, x0: 985, x1: 1115, uMax: 1 }, { y: 745, x0: 985, x1: 1115, uMax: 1 }, { y: 785, x0: 985, x1: 1115, uMax: 0.65 }];
const AMP = 5, WAVES = 5;
const point = (k, u) => { const L = LINES[k]; return [L.x0 + (L.x1 - L.x0) * u, L.y + AMP * Math.sin(2 * Math.PI * WAVES * u)]; };
const TL = [ // loop timeline (ms)
  { type: 'line', k: 0, t0: 0, t1: 900 }, { type: 'move', from: [0, 1], to: [1, 0], t0: 900, t1: 1150 },
  { type: 'line', k: 1, t0: 1150, t1: 2050 }, { type: 'move', from: [1, 1], to: [2, 0], t0: 2050, t1: 2300 },
  { type: 'line', k: 2, t0: 2300, t1: 3000 }, { type: 'move', from: [2, 0.65], to: [0, 0], t0: 3000, t1: 3600 },
];
const LOOP = 3600, ENTRY = 450;
const frames = [];
const pushFrame = (t, P, lift = 0) => frames.push({ t, tr: translateFor(P, lift) });
for (const seg of TL) {
  if (seg.type === 'line') { const L = LINES[seg.k]; const n = 28; for (let j = 0; j <= n; j++) { const u = (j / n) * L.uMax; pushFrame(seg.t0 + ((seg.t1 - seg.t0) * j) / n, point(seg.k, u)); } }
  else { const a = point(seg.from[0], seg.from[1]), b = point(seg.to[0], seg.to[1]); const n = 8; for (let j = 0; j <= n; j++) { const m = j / n, e = m * m * (3 - 2 * m); pushFrame(seg.t0 + (seg.t1 - seg.t0) * m, [a[0] + (b[0] - a[0]) * e, a[1] + (b[1] - a[1]) * e], 11 * Math.sin(Math.PI * m)); } }
}
const pc = (v, d) => `${((v / d) * 100).toFixed(3)}%`;
const tf = (tr, deg) => `translate(${pc(tr[0], STAGE.w)}, ${pc(tr[1], STAGE.h)}) rotate(${deg}deg)`;
const dedup = []; for (const f of frames) if (!dedup.length || f.t !== dedup[dedup.length - 1].t) dedup.push(f);
const start = dedup[0].tr;
let css = `/* GENERATED by scripts/mino-art/gen-rig-writing.mjs — do not edit by hand.
 * Writing: the pencil tip follows the three handwriting strokes drawn on the notebook (tip error ≈ 0 by construction;
 * verified in the browser by scripts/e2e/mino-rig.e2e.ts). Entry eases into the pose, then a ${LOOP} ms loop writes line 1-3. */
@keyframes rig-write-in-arm-l { from { transform: translate(0, 0) rotate(0deg); } to { transform: ${tf(start, TH_ARM)}; } }
@keyframes rig-write-loop-arm-l {\n${dedup.map((f) => `  ${((f.t / LOOP) * 100).toFixed(3)}% { transform: ${tf(f.tr, TH_ARM)}; }`).join('\n')}\n}
@keyframes rig-write-in-pencil { from { transform: rotate(0deg); } to { transform: rotate(${TH_WRIST}deg); } }
@keyframes rig-write-in-arm-r { from { transform: rotate(0deg); } to { transform: rotate(${TH_R}deg); } }
@keyframes rig-write-in-head { from { transform: rotate(0deg) translateY(0); } to { transform: rotate(-1.4deg) translateY(0.35%); } }
@keyframes rig-write-in-gaze { from { transform: translate(0, 0); } to { transform: translate(0.45%, 0.8%); } }
@keyframes rig-write-s1 { 0% { stroke-dashoffset: 1; } ${((900 / LOOP) * 100).toFixed(3)}%, 100% { stroke-dashoffset: 0; } }
@keyframes rig-write-s2 { 0%, ${((1150 / LOOP) * 100).toFixed(3)}% { stroke-dashoffset: 1; } ${((2050 / LOOP) * 100).toFixed(3)}%, 100% { stroke-dashoffset: 0; } }
@keyframes rig-write-s3 { 0%, ${((2300 / LOOP) * 100).toFixed(3)}% { stroke-dashoffset: 1; } ${((3000 / LOOP) * 100).toFixed(3)}%, 100% { stroke-dashoffset: 0; } }
@keyframes rig-write-stroke-fade { 0%, 88% { opacity: 0.9; } 100% { opacity: 0; } }
.mino-rig[data-state='writing'] .mino-rig__arm-l { animation: rig-write-in-arm-l ${ENTRY}ms ease-out both, rig-write-loop-arm-l ${LOOP}ms linear ${ENTRY}ms infinite; }
.mino-rig[data-state='writing'] .mino-rig__pencil { animation: rig-write-in-pencil ${ENTRY}ms ease-out both; }
.mino-rig[data-state='writing'] .mino-rig__arm-r { animation: rig-write-in-arm-r ${ENTRY}ms ease-out both; }
.mino-rig[data-state='writing'] .mino-rig__head { animation: rig-write-in-head ${ENTRY}ms ease-out both; }
.mino-rig[data-state='writing'] .mino-rig__eyes { animation: rig-write-in-gaze ${ENTRY}ms ease-out both; }
.mino-rig[data-state='writing'] .mino-rig__stroke { animation: rig-write-stroke-fade ${LOOP}ms linear ${ENTRY}ms infinite; }
.mino-rig[data-state='writing'] .mino-rig__stroke path:nth-child(1) { animation: rig-write-s1 ${LOOP}ms linear ${ENTRY}ms infinite; }
.mino-rig[data-state='writing'] .mino-rig__stroke path:nth-child(2) { animation: rig-write-s2 ${LOOP}ms linear ${ENTRY}ms infinite; }
.mino-rig[data-state='writing'] .mino-rig__stroke path:nth-child(3) { animation: rig-write-s3 ${LOOP}ms linear ${ENTRY}ms infinite; }
`;
fs.writeFileSync(new URL('../../components/mino/dev/mino-rig-writing.generated.css', import.meta.url), css);
const poly = (k) => { const L = LINES[k]; const n = 60; return 'M' + Array.from({ length: n + 1 }, (_, j) => point(k, (j / n) * L.uMax).map((v) => v.toFixed(1)).join(' ')).join(' L'); };
const ts = `/* GENERATED by scripts/mino-art/gen-rig-writing.mjs — do not edit by hand. Notebook-local master px. */
export const WRITING_STROKE_PATHS: string[] = ${JSON.stringify([0, 1, 2].map(poly), null, 2)};
export const WRITING_NOTEBOOK_DEG = ${TH_R};
export const WRITING_ENTRY_MS = ${ENTRY};
export const WRITING_LOOP_MS = ${LOOP};
export const WRITING_PENCIL_TIP: [number, number] = [${T0[0]}, ${T0[1]}];
export const WRITING_LINES = ${JSON.stringify(LINES)} as const;
export const WRITING_AMP = ${AMP};
export const WRITING_WAVES = ${WAVES};
/** Timeline segments inside the loop (ms): lines are being written, moves are the pencil lifting between lines. */
export const WRITING_TIMELINE = ${JSON.stringify(TL)} as const;
/** Notebook-local point of line k at progress u (0..1 of that line). */
export function writingPoint(k: number, u: number): [number, number] {
  const L = WRITING_LINES[k];
  return [L.x0 + (L.x1 - L.x0) * u, L.y + WRITING_AMP * Math.sin(2 * Math.PI * WRITING_WAVES * u)];
}
`;
fs.writeFileSync(new URL('../../components/mino/dev/coach-rig-writing.generated.ts', import.meta.url), ts);
console.log('keyframes', dedup.length, 'start translate', start.map((v) => v.toFixed(1)));
